"""Publish station design conditions, archetype defaults and the sampled
design space to web/data/loads-data.js for the browser.

Usage:  python3 engine/build_data.py
Re-run after editing stations.json, archetypes.json or variables.json.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from lib import scenario, weather  # noqa: E402

OUT_JS = os.path.join(os.path.dirname(HERE), 'web', 'data', 'loads-data.js')


def station_record(st):
    stem = os.path.basename(st['path'])
    base = os.path.join(HERE, 'weather', stem)
    ddy = weather.parse_ddy(base + '.ddy')
    stat = weather.parse_stat(base + '.stat')
    dds = {}
    for key in weather.DESIGN_DAY_KEYS:
        d = ddy['design_days'].get(key)
        if not d:
            continue
        rec = {'name': d['name'], 'month': d['month'], 'day': d['day'], 'db_c': d['max_db_c'],
               'db_range_c': d['db_range_c']}
        ht = (d['humidity_type'] or '').lower()
        if key.startswith('htg'):
            pass   # heating days carry a placeholder wet-bulb equal to the dry-bulb
        elif ht == 'wetbulb':
            rec['mcwb_c'] = d['humidity_value']
        elif ht == 'dewpoint':
            rec['dp_c'] = d['humidity_value']
        dds[key] = rec
    loc = ddy['location']
    return {
        'id': st['id'], 'label': st['label'], 'file': stem,
        'lat': loc['latitude'], 'lon': loc['longitude'], 'elev_m': loc['elevation_m'],
        'climate_zone_stat': stat['climate_zone'],
        'design_source': ddy['source_note'],
        'design_days': dds,
    }


def main():
    with open(os.path.join(HERE, 'stations.json')) as f:
        manifest = json.load(f)
    with open(os.path.join(HERE, 'archetypes.json')) as f:
        arch = json.load(f)
    with open(os.path.join(HERE, 'variables.json')) as f:
        space = json.load(f)
    payload = {
        'stations': [station_record(s) for s in manifest['stations']],
        'stations_source': manifest['_source'],
        'archetypes': arch,
        'design_space': space,
        'fields': scenario.FIELDS,
    }
    with open(OUT_JS, 'w') as f:
        f.write('// Generated by engine/build_data.py - do not edit by hand.\n')
        f.write('// Station design conditions are read verbatim from the DOE EnergyPlus .ddy files.\n')
        f.write('var LOADS_DATA = ' + json.dumps(payload, indent=1) + ';\n')
    print('wrote', OUT_JS, len(payload['stations']), 'stations')


if __name__ == '__main__':
    main()
