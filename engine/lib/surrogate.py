"""Evaluate a published surrogate in Python exactly as the page does
(web/core.js predict + surrogateResult). Used by validate.py; parity with the
JavaScript is checked in tests/test_validate.py.
"""
import json
import os

from . import features


# Published layout (all under web/data/):
#   loads-surrogate.js                small index: which models exist + their summary
#   surrogates/<type>__<station>.js   one file per model, loaded by the page on demand
# so the page stays light with hundreds of models.
INDEX_FIELDS = ('type', 'station', 'climate_zone', 'n_samples', 'eplus_versions', 'fitted_at', 'holdout')


def _model_dir(index_path):
    return os.path.join(os.path.dirname(index_path), 'surrogates')


def _model_file(index_path, key):
    return os.path.join(_model_dir(index_path), key.replace('|', '__') + '.js')


def _read_js_json(path):
    """JSON payload of a generated .js file: `var X = {...};` or `(...)["key"] = {...};`."""
    with open(path) as f:
        txt = f.read()
    start = txt.index('] = ') + 4 if '] = ' in txt else txt.index('= ') + 2
    return json.loads(txt[start:].strip().rstrip(';'))


def load_published(path):
    """Read the published index and every model file -> {'meta', 'models'}."""
    data = _read_js_json(path)
    if data.get('models'):             # older single-file layout
        return {'meta': data.get('meta', {}), 'models': data['models']}
    models = {}
    for key in data.get('index', {}):
        mf = _model_file(path, key)
        if os.path.exists(mf):
            models[key] = _read_js_json(mf)
    return {'meta': data.get('meta', {}), 'models': models}


def _compact(model):
    """6 significant figures on coefficients: far below the fit error, ~40% smaller."""
    m = dict(model)
    m['outputs'] = {k: dict(o, coef=[float('%.6g' % c) for c in o['coef']]) for k, o in model['outputs'].items()}
    return m


def write_published(path, payload):
    os.makedirs(_model_dir(path), exist_ok=True)
    index = {}
    for key, model in sorted(payload['models'].items()):
        index[key] = {k: model.get(k) for k in INDEX_FIELDS}
        with open(_model_file(path, key), 'w') as f:
            f.write('// Generated by engine/fit_surrogate.py - do not edit by hand.\n')
            f.write('(window.LOADS_SURROGATE_MODELS = window.LOADS_SURROGATE_MODELS || {})[%s] = ' % json.dumps(key))
            f.write(json.dumps(_compact(model), separators=(',', ':')) + ';\n')
    with open(path, 'w') as f:
        f.write('// Generated by engine/fit_surrogate.py - do not edit by hand.\n')
        f.write('// Index of EnergyPlus-trained peak-load surrogates; each model is in surrogates/<type>__<station>.js\n')
        f.write('var LOADS_SURROGATE = ' + json.dumps({'meta': payload.get('meta', {}), 'index': index},
                                                       separators=(',', ':')) + ';\n')


def _expand(z):
    out = [1.0] + list(z)
    for i in range(len(z)):
        for j in range(i, len(z)):
            out.append(z[i] * z[j])
    return out


def predict(model, sc):
    """Per-m2 outputs for a resolved scenario, with the page's clamps applied.

    Returns (outputs, extrapolated_feature_names). Raises ValueError when the
    model was fitted with a different feature list.
    """
    if model.get('features') != features.FEATURES:
        raise ValueError('surrogate was fitted with a different feature set; refit it')
    x = features.features(sc)
    z = [(x[i] - model['feature_mean'][i]) / model['feature_std'][i] for i in range(len(x))]
    extrap = []
    for i, v in enumerate(x):
        lo, hi = model['feature_min'][i], model['feature_max'][i]
        tol = 1e-9 + 0.03 * abs(hi - lo)
        if v < lo - tol or v > hi + tol:
            extrap.append(features.FEATURES[i])
    X = _expand(z)
    no_recovery = not (sc['erv_sensible_eff'] > 0) and not (sc['erv_latent_eff'] > 0)
    out = {}
    for name, o in model['outputs'].items():
        v = sum(c * xx for c, xx in zip(o['coef'], X))
        if not name.startswith('comp_'):
            v = max(0.0, v)       # loads can't be negative; components can
        if name.endswith('|hr_w_m2') and no_recovery:
            v = 0.0
        out[name] = v
    return out, extrap
